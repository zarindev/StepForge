  public WebElement find(List<Sel> selectors, int seconds) {
    long deadline = System.currentTimeMillis() + seconds * 1000L;
    while (true) {
      List<WebElement> found = all(selectors);
      if (!found.isEmpty()) return found.get(0);
      if (System.currentTimeMillis() >= deadline)
        throw new AssertionError("No element found within " + seconds + " s: " + selectors);
      sleep(250);
    }
  }

