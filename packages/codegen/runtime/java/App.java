  /** Waits until the check passes (as StepForge's assert step), else fails with what was seen. */
  public void expect(String check, List<Sel> selectors, Object expected, String attribute) {
    long deadline = System.currentTimeMillis() + timeout * 1000L;
    while (true) {
      String[] seen = new String[1];
      if (check(check, selectors, expected, attribute, seen)) return;
      if (System.currentTimeMillis() >= deadline)
        throw new AssertionError("Expected " + check + (expected == null ? "" : " \"" + expected + "\"") + ", but got " + seen[0]);
      sleep(250);
    }
  }

  private boolean check(String check, List<Sel> selectors, Object expected, String attribute, String[] seen) {
    try {
      List<WebElement> found = all(selectors);
      if (check.equals("count")) {
        seen[0] = found.size() + " found";
        return found.size() == Integer.parseInt(String.valueOf(expected));
      }
      if (check.equals("hidden")) {
        boolean visible = !found.isEmpty() && found.get(0).isDisplayed();
        seen[0] = visible ? "visible" : "not visible";
        return !visible;
      }
      if (found.isEmpty()) {
        seen[0] = "not found";
        return false;
      }
      WebElement el = found.get(0);
      switch (check) {
        case "visible" -> {
          seen[0] = "present but not visible";
          return el.isDisplayed();
        }
        case "enabled", "disabled" -> {
          boolean enabled = el.isEnabled();
          seen[0] = enabled ? "enabled" : "disabled";
          return enabled == check.equals("enabled");
        }
        case "checked", "unchecked" -> {
          boolean checked = isChecked(el);
          seen[0] = checked ? "checked" : "unchecked";
          return checked == check.equals("checked");
        }
        case "attribute" -> {
          String value = el.getAttribute(attribute);
          seen[0] = "\"" + value + "\"";
          return String.valueOf(expected).equals(value);
        }
        default -> {
          String text = el.getText() == null ? "" : el.getText().trim();
          seen[0] = "\"" + text + "\"";
          return switch (check) {
            case "text", "value" -> text.equals(String.valueOf(expected));
            case "textContains" -> text.contains(String.valueOf(expected));
            case "textMatches" -> Pattern.compile(String.valueOf(expected)).matcher(text).find();
            default -> throw new IllegalArgumentException("Unknown check \"" + check + "\"");
          };
        }
      }
    } catch (WebDriverException e) {
      seen[0] = "not ready (" + e.getMessage().split("\n")[0] + ")";
      return false;
    }
  }

