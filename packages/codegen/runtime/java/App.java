  /** The elements the first matching selector finds now (no waiting), or an empty list. */
  public List<WebElement> all(List<Sel> selectors) {
    for (Sel s : selectors) {
      List<WebElement> found;
      try {
        found = driver.findElements(new Raw(s));
      } catch (WebDriverException e) {
        if (String.valueOf(e.getMessage()).toLowerCase().contains("invalid selector"))
          throw new AssertionError("Invalid locator " + s.using() + "=" + s.value() + ": " + e.getMessage());
        found = List.of();
      }
      if (!found.isEmpty()) return found;
    }
    return List.of();
  }

