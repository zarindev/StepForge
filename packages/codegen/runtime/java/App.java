  /** Scrolls the screen; false when it could not move any more (Android says so). */
  public boolean scroll(String direction) {
    boolean down = direction.equals("down");
    switch (platform) {
      case "android" -> {
        Map<String, Object> args = area();
        args.put("direction", direction);
        args.put("percent", 0.75);
        return Boolean.TRUE.equals(run("mobile: scrollGesture", args));
      }
      // On iOS a swipe up moves the content down.
      case "ios" -> run("mobile: swipe", Map.of("direction", down ? "up" : "down"));
      case "macos" -> run("macos: scroll", Map.of("x", 400, "y", 300, "deltaX", 0, "deltaY", down ? -200 : 200));
      case "windows" -> run("windows: scroll", Map.of("deltaY", down ? -360 : 360));
      default -> shortcut(down ? "PageDown" : "PageUp");
    }
    return true;
  }

