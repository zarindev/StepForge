  /** Looks, scrolls, looks again, until the element shows or the screen stops moving. */
  public void scrollTo(List<Sel> selectors, String direction, int maxSwipes) {
    int stuck = 0;
    for (int i = 0; i <= maxSwipes; i++) {
      List<WebElement> found = all(selectors);
      if (!found.isEmpty() && Boolean.TRUE.equals(attempt(found.get(0)::isDisplayed))) return;
      if (i == maxSwipes || stuck >= 2) break;
      String before = attempt(driver::getPageSource);
      scroll(direction);
      sleep(400);
      String after = attempt(driver::getPageSource);
      stuck = before != null && before.equals(after) ? stuck + 1 : 0;
    }
    throw new AssertionError("Scrolled " + direction + " and the element did not show: " + selectors);
  }

