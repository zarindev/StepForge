  public void press(String key, List<Sel> selectors) {
    WebElement el = selectors == null ? null : find(selectors);
    if (el != null) el.click();
    if (platform.equals("android")) {
      if (key.equals("Back")) {
        driver.navigate().back();
        return;
      }
      Integer code = ANDROID_KEYS.get(key);
      if (code == null) throw new AssertionError("The key \"" + key + "\" is not available on Android");
      run("mobile: pressKey", Map.of("keycode", code));
    } else if (platform.equals("ios")) {
      if (key.equals("Home")) {
        run("mobile: pressButton", Map.of("name", "home"));
        return;
      }
      String text = IOS_KEYS.get(key);
      if (text == null) throw new AssertionError("The key \"" + key + "\" is not available on iOS");
      (el != null ? el : driver.switchTo().activeElement()).sendKeys(text);
    } else shortcut(key);
  }

  /** A key or a shortcut ("Control+S") with W3C key actions: modifiers down, the key, modifiers up. */
  public void shortcut(String combo) {
    List<String> keys = new ArrayList<>();
    for (String raw : combo.split("\\+")) {
      String k = raw.trim();
      if (k.isEmpty()) continue;
      String v = W3C_KEYS.getOrDefault(k, W3C_KEYS.get(k.substring(0, 1).toUpperCase() + k.substring(1)));
      if (v == null && k.length() == 1) v = k;
      if (v == null) throw new AssertionError("Unknown key \"" + k + "\" in \"" + combo + "\"");
      keys.add(v);
    }
    KeyInput keyboard = new KeyInput("keyboard");
    Sequence seq = new Sequence(keyboard, 0);
    for (String k : keys) seq.addAction(keyboard.createKeyDown(k.codePointAt(0)));
    for (int i = keys.size() - 1; i >= 0; i--) seq.addAction(keyboard.createKeyUp(keys.get(i).codePointAt(0)));
    driver.perform(List.of(seq));
  }

