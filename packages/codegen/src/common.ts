/** GitHub Actions and/or GitLab CI files; secrets come from the CI's secret store. */
export function ciFiles(plan: Plan, family: Family, providers: CiProvider[] = []): Record<string, string> {
  const env = envEntries(plan);
  const isSecret = (k: string) => plan.secrets.some((s) => envName(s) === k) || k.startsWith('DB_');
  const out: Record<string, string> = {};
  if (providers.includes('github'))
    out['.github/workflows/stepforge-tests.yml'] = [
      `# ${CREDIT}`,
      `name: ${plan.input.application.name} tests`,
      'on:',
      '  push:',
      '  workflow_dispatch:',
      'jobs:',
      '  tests:',
      '    runs-on: ubuntu-latest',
      '    env:',
      ...env.map((e) =>
        isSecret(e.key)
          ? `      ${e.key}: \${{ secrets.${e.key} }}`
          : `      ${e.key}: \${{ vars.${e.key} || '${e.value.replace(/'/g, "''")}' }}`,
      ),
      '    steps:',
      '      - uses: actions/checkout@v4',
      ...SETUP[family].github,
      '',
    ].join('\n');
  if (providers.includes('gitlab'))
    out['.gitlab-ci.yml'] = [
      `# ${CREDIT}`,
      '# Set the secret variables (masked) in Settings → CI/CD → Variables.',
      'tests:',
      `  image: ${SETUP[family].gitlabImage}`,
      '  variables:',
      ...env.filter((e) => !isSecret(e.key)).map((e) => `    ${e.key}: "${e.value.replace(/"/g, '\\"')}"`),
      '  script:',
      ...SETUP[family].gitlab.map((c) => `    - ${c}`),
      '',
    ].join('\n');
  return out;
}

/** Test-case rows (or a single row without data). */
export const casesOf = (s: CodegenScenario) =>
  s.testCases.length ? s.testCases : [{ code: '', title: '', data: {} as Record<string, unknown> }];
